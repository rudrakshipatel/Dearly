/**
 * Generates supabase/seed.sql from the app's TypeScript catalogue so the database and UI never drift.
 * Run: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from "node:fs";
import { buildCreation, seededIds } from "../src/lib/creation";
import { creationToCardData } from "../src/lib/card-engine/convert";
import { validateCardData } from "../src/lib/card-engine/schema";
import { PLAN_LIMITS } from "../src/lib/entitlements";
import { occasions } from "../src/lib/data/occasions";
import { palettes } from "../src/lib/data/palettes";
import { sampleCreations } from "../src/lib/data/samples";
import { templates } from "../src/lib/data/templates";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const slugOf = (id: string) => id.replace(/^tpl-/, "");
const out: string[] = ["-- Generated by scripts/generate-seed.ts — do not edit by hand.", "begin;"];

out.push("-- Plan limits");
for (const [plan, l] of Object.entries(PLAN_LIMITS)) {
  out.push(
    `insert into public.plan_limits values (${q(plan)}, ${l.maxLiveCards}, ${l.maxPhotosPerCard}, ${l.maxPages}, ${l.maxVideoSeconds}, ${l.allowVideoAudio}, ${l.allowPremiumTemplates}, ${l.allowRemoveBranding}, ${l.allowScheduling}, ${l.maxGroupContributors}, ${l.aiGenerationsPerMonth}, ${l.storageBytes}, ${l.maxImageBytes}, ${l.maxVideoBytes}, ${l.maxAudioBytes})
  on conflict (plan) do update set max_live_cards = excluded.max_live_cards, max_photos_per_card = excluded.max_photos_per_card, max_pages = excluded.max_pages, max_video_seconds = excluded.max_video_seconds, allow_video_audio = excluded.allow_video_audio, allow_premium_templates = excluded.allow_premium_templates, allow_remove_branding = excluded.allow_remove_branding, allow_scheduling = excluded.allow_scheduling, max_group_contributors = excluded.max_group_contributors, ai_generations_per_month = excluded.ai_generations_per_month, storage_bytes = excluded.storage_bytes, max_image_bytes = excluded.max_image_bytes, max_video_bytes = excluded.max_video_bytes, max_audio_bytes = excluded.max_audio_bytes;`,
  );
}

out.push("-- Occasions");
occasions.forEach((o, i) => {
  const theme = { palette: o.palette, motif: o.motif, colors: palettes[o.palette], short: o.short, headline: o.headline, suggested: o.suggested, related: o.related, prompts: o.prompts };
  out.push(
    `insert into public.occasions (name, slug, description, theme_config, sort_order, is_active) values (${q(o.name)}, ${q(o.slug)}, ${q(o.description)}, ${j(theme)}, ${i}, true)
  on conflict (slug) do update set name = excluded.name, description = excluded.description, theme_config = excluded.theme_config, sort_order = excluded.sort_order;`,
  );
});

out.push("-- Templates");
for (const t of templates) {
  const preview = { palette: t.palette, motif: t.motif, headline: t.headline, font: t.font, pages: t.pages, photoSlots: t.photoSlots, category: t.category, popularity: t.popularity, addedAt: t.addedAt };
  const draft = buildCreation({ template: t, recipientName: "", senderName: "", now: "2026-01-01T00:00:00.000Z", id: seededIds(slugOf(t.id).replace(/-/g, "").slice(0, 8)) });
  const data = creationToCardData(draft);
  const v = validateCardData(data);
  if (!v.ok) throw new Error(`Template ${t.id} default card invalid: ${v.path} ${v.error}`);
  out.push(
    `insert into public.templates (name, slug, description, occasion_id, experience_type, preview_data, default_card_data, supported_interactions, style_category, is_premium, is_published)
  values (${q(t.name)}, ${q(slugOf(t.id))}, ${q(t.description)}, (select id from public.occasions where slug = ${q(t.occasion)}), ${q(t.experience)}, ${j(preview)}, ${j(data)}, ${j(t.interactions)}, ${q(t.style)}, ${t.premium}, true)
  on conflict (slug) do update set name = excluded.name, description = excluded.description, occasion_id = excluded.occasion_id, experience_type = excluded.experience_type, preview_data = excluded.preview_data, default_card_data = excluded.default_card_data, supported_interactions = excluded.supported_interactions, style_category = excluded.style_category, is_premium = excluded.is_premium;`,
  );
}

out.push("-- Sample cards (system-owned, always public) used by the marketing pages");
for (const c of sampleCreations) {
  const data = creationToCardData(c);
  const v = validateCardData(data);
  if (!v.ok) throw new Error(`Sample ${c.slug} invalid: ${v.path} ${v.error}`);
  const t = templates.find((x) => x.id === c.templateId)!;
  out.push(
    `insert into public.cards (is_sample, title, recipient_name, sender_name, occasion_id, template_id, experience_type, slug, status, card_data, published_at, show_branding, allow_reactions, contribution_token, contributions_require_approval)
  values (true, ${q(c.title)}, ${q(c.recipientName)}, ${q(c.senderName)}, (select id from public.occasions where slug = ${q(c.occasion)}), (select id from public.templates where slug = ${q(slugOf(t.id))}), ${q(c.experience)}, ${q(c.slug)}, 'published', ${j(data)}, '2026-10-29T18:00:00Z', true, true, ${c.slug === "happy-birthday-leo" ? "'DemoGroupCardHappyBirthdayLeo2026'" : "null"}, true)
  on conflict (slug) do update set card_data = excluded.card_data, title = excluded.title, experience_type = excluded.experience_type, template_id = excluded.template_id, contribution_token = excluded.contribution_token, contributions_require_approval = true;`,
  );
  for (const k of c.contributions ?? []) {
    const media = k.photo ? [{ type: "image", src: k.photo }] : [];
    out.push(
      `insert into public.group_contributions (card_id, contributor_name, message, color, media_references, status, approved_at, submitted_at)
  select id, ${q(k.name)}, ${q(k.message)}, ${q(k.color)}, ${j(media)}, 'approved', now(), '2026-10-29T18:00:00Z' from public.cards where slug = ${q(c.slug)}
  and not exists (select 1 from public.group_contributions g join public.cards cc on cc.id = g.card_id where cc.slug = ${q(c.slug)} and g.contributor_name = ${q(k.name)});`,
    );
  }
}
out.push("commit;");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql: ${PLAN_LIMITS ? 3 : 0} plans, ${occasions.length} occasions, ${templates.length} templates, ${sampleCreations.length} samples`);
